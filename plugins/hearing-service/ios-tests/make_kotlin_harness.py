#!/usr/bin/env python3
"""
Build the Kotlin side of the VAD parity check by lifting the detector
VERBATIM out of ../kotlin/HearingService.kt: its constants, its state
fields, and every method from processFrame up to (not including)
emitEvent. Only the Android event plumbing is replaced, by a recorder that
prints the same line format as main.swift. Nothing in the lifted
code is edited, so the check runs the code Android actually ships.

Usage: make_kotlin_harness.py ../kotlin/HearingService.kt OUT.kt
"""
import re, sys

src = open(sys.argv[1]).read().splitlines()

def find(pred, start=0):
    for i in range(start, len(src)):
        if pred(src[i]):
            return i
    raise SystemExit(f"anchor not found from line {start}")

consts = [l for l in src if re.match(r"\s*(private )?const val ", l) and "TAG" not in l]
f0 = find(lambda l: l.strip().startswith("private val preRoll = ShortArray"))
f1 = find(lambda l: "calibrationFramesTarget" in l and l.strip().startswith("private val"), f0)
fields = src[f0:f1 + 1]
m0 = find(lambda l: l.strip().startswith("private fun processFrame("))
m1 = find(lambda l: l.strip().startswith("private fun emitEvent("), m0)
methods = src[m0:m1]

if len(consts) < 15 or len(methods) < 100:
    raise SystemExit(f"suspiciously little extracted: {len(consts)} consts, {len(methods)} method lines")

out = f'''// GENERATED by make_kotlin_harness.py from HearingService.kt. Do not edit.
import java.nio.ByteBuffer
import java.nio.ByteOrder

class WritableMap {{
  val m = LinkedHashMap<String, Any?>()
  fun putBoolean(k: String, v: Boolean) {{ m[k] = v }}
  fun putDouble(k: String, v: Double) {{ m[k] = v }}
  fun putString(k: String, v: String?) {{ m[k] = v }}
  fun putInt(k: String, v: Int) {{ m[k] = v }}
}}
object Arguments {{ fun createMap() = WritableMap() }}
object Base64 {{
  const val NO_WRAP = 2
  fun encodeToString(b: ByteArray, flags: Int): String = java.util.Base64.getEncoder().encodeToString(b)
}}

fun fnv1a(s: String): ULong {{
  var h = 0xcbf29ce484222325UL
  for (b in s.toByteArray(Charsets.UTF_8)) {{ h = h xor b.toUByte().toULong(); h *= 0x100000001b3UL }}
  return h
}}
fun bits(d: Double): String = java.lang.Long.toHexString(java.lang.Double.doubleToRawLongBits(d))

class Harness {{
  companion object {{
{chr(10).join(consts)}
  }}

{chr(10).join(fields)}

  val lines = ArrayList<String>()

  private fun emitEvent(name: String, payload: WritableMap) {{
    val m = payload.m
    when (name) {{
      "HearingTick" -> lines.add(
        "T speech=${{m["speech"]}} rms=${{bits(m["rms"] as Double)}} nf=${{bits(m["noiseFloor"] as Double)}} " +
          "cal=${{m["calibrating"]}} total=${{bits(m["totalMs"] as Double)}} speechMs=${{bits(m["speechMs"] as Double)}}"
      )
      "HearingSpeechSegment" -> {{
        val b64 = m["pcmBase64"] as String
        val samples = java.util.Base64.getDecoder().decode(b64).size / 2
        lines.add("S dur=${{(m["durationMs"] as Double).toLong()}} samples=$samples b64len=${{b64.length}} b64fnv=${{fnv1a(b64).toString(16)}}")
      }}
    }}
  }}

{chr(10).join(methods)}

  fun run(pcm: ShortArray) {{
    val frame = ShortArray(FRAME_SAMPLES)
    var off = 0
    while (off + FRAME_SAMPLES <= pcm.size) {{
      System.arraycopy(pcm, off, frame, 0, FRAME_SAMPLES)
      processFrame(frame, FRAME_SAMPLES)
      off += FRAME_SAMPLES
    }}
    lines.add("E totalFrames=$totalFrames speechFrames=$speechFrames segments=$segmentsEmitted")
  }}
}}

fun main() {{
  val pcm = generateSequence(::readLine).map {{ it.trim().toShort() }}.toList().toShortArray()
  val h = Harness()
  h.run(pcm)
  println(h.lines.joinToString("\\n"))
}}
'''
open(sys.argv[2], "w").write(out)
print(f"extracted {len(consts)} constants, {len(fields)} field lines, {len(methods)} method lines")
